const KEY = 'gradula-language';

/**
 * Which language. The stored choice first, then the browser's, then German —
 * German because whoever has not chosen is standing in this house, and this
 * house speaks German out loud even where its code does not.
 */
export function chosenLanguage(): Language {
  try {
    const held = localStorage.getItem(KEY);
    if (held === 'de' || held === 'en') return held;
  } catch { /* a browser that forbids storage still gets a language */ }
  const asked = (globalThis.navigator?.language ?? '').slice(0, 2).toLowerCase();
  return asked === 'en' ? 'en' : 'de';
}

/** Remember the choice. The page is reloaded by the caller, not here. */
export function keepLanguage(language: Language): void {
  try { localStorage.setItem(KEY, language); } catch { /* then it holds for this visit */ }
}

/**
 * A word for people. A missing twin comes back as the KEY, not as an empty
 * string: a surface with a visible identifier is ugly, one without text is
 * broken, and only the ugly one gets fixed.
 *
 * The `fallback` is for words that COME FROM THE SERVICE with a sentence
 * already attached — a finding, say. The service names it in English and the
 * surface may know it better; a finding this surface has never heard of still
 * shows the service's own line rather than an identifier.
 */
export function words(language: Language) {
  const surface = SURFACE[language] ?? SURFACE.de;
  const vocabulary = WORDS[language] ?? WORDS.de;
  return (key: string, fallback?: string): string => surface[key] ?? vocabulary[key] ?? fallback ?? key;
}
